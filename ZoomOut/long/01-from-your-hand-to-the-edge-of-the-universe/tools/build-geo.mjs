// Offline: re-project ep 15's real NYC coastlines (orthographic about Lower Manhattan, rolled -29 deg) into this
// episode's frame: orthographic about HAND (the Sheep Meadow), north up, metres (x east, y south). Writes geo.js.
//   node tools/build-geo.mjs
import fs from 'node:fs';
// earth.js fetches its elevation data at import, so its (pure) view maths is mirrored here verbatim.
const DEG = Math.PI / 180;
function basis(view) {
  const lam = ((view.lon0 ?? 0) - (view.rot ?? 0)) * DEG, phi = (view.lat0 ?? 0) * DEG, t = (view.tilt ?? 0) * DEG;
  const cl = Math.cos(lam), sl = Math.sin(lam), cp = Math.cos(phi), sp = Math.sin(phi);
  const c = [cp * cl, cp * sl, sp], r0 = [-sl, cl, 0], u0 = [-sp * cl, -sp * sl, cp];
  const ct = Math.cos(t), st = Math.sin(t);
  return {
    r: [ct * r0[0] + st * u0[0], ct * r0[1] + st * u0[1], ct * r0[2] + st * u0[2]],
    u: [-st * r0[0] + ct * u0[0], -st * r0[1] + ct * u0[1], -st * r0[2] + ct * u0[2]],
    c,
  };
}
const vec = (lat, lon) => [Math.cos(lat * DEG) * Math.cos(lon * DEG), Math.cos(lat * DEG) * Math.sin(lon * DEG), Math.sin(lat * DEG)];
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
function project(lat, lon, view) {
  const b = basis(view), p = vec(lat, lon);
  return { x: view.cx + dot(p, b.r) * view.r, y: view.cy - dot(p, b.u) * view.r };
}
function unproject(x, y, view) {
  const b = basis(view);
  const X = (x - view.cx) / view.r, Y = (view.cy - y) / view.r, Z = Math.sqrt(Math.max(0, 1 - X * X - Y * Y));
  const px = X * b.r[0] + Y * b.u[0] + Z * b.c[0], py = X * b.r[1] + Y * b.u[1] + Z * b.c[1], pz = X * b.r[2] + Y * b.u[2] + Z * b.c[2];
  return { lat: Math.asin(Math.max(-1, Math.min(1, pz))) / DEG, lon: Math.atan2(py, px) / DEG };
}
import * as G from '../../../episodes/15-what-if-humans-disappeared/geo-nyc.js';

const R = 6.371e6;
const SRC = { cx: 0, cy: 0, r: R, lat0: 40.704869047, lon0: -74.012910625, rot: 0, tilt: -29 };
// Sheep Meadow centre, located in ep 15's frame (Central Park rect x -1126..-270, south edge y -7416, 59th St):
// 66th-69th St band (~700 m north of 59th St), west-centre of the park.
const meadow = unproject(-790, -8110, SRC);
const DST = { cx: 0, cy: 0, r: R, lat0: meadow.lat, lon0: meadow.lon, rot: 0, tilt: 0 };
const conv = (rings) => rings.map((r) => {
  const out = new Array(r.length);
  for (let i = 0; i < r.length; i += 2) {
    const g = unproject(r[i], r[i + 1], SRC);
    const p = project(g.lat, g.lon, DST);
    out[i] = Math.round(p.x); out[i + 1] = Math.round(p.y);
  }
  return out;
});
const park = [[-1126, -11548], [-270, -11548], [-270, -7416], [-1126, -7416]].map(([x, y]) => {
  const g = unproject(x, y, SRC); const p = project(g.lat, g.lon, DST); return [Math.round(p.x), Math.round(p.y)];
});
let s = `// GENERATED by tools/build-geo.mjs: real coastlines around New York (NYC DCP borough shorelines + US Census 500k
// counties, via ep 15), orthographic about HAND (the Sheep Meadow, Central Park), north up, metres: x east, y south.
// Flat [x0,y0,x1,y1,...] rings; exteriors and holes wound oppositely (fill 'nonzero'). earth.js drawEarth with
// lat0/lon0 = HAND and tilt 0 lines up with these exactly.
export const HAND = { lat: ${meadow.lat.toFixed(7)}, lon: ${meadow.lon.toFixed(7)} };
export const CENTRAL_PARK = ${JSON.stringify(park)};   // corners (SW→ rotated): the park rectangle in this frame
`;
for (const k of ['FINE', 'MED', 'COARSE', 'CITY']) s += `export const ${k} = ${JSON.stringify(conv(G[k]))};\n`;
fs.writeFileSync('geo.js', s);
console.log('HAND', meadow, 'park', JSON.stringify(park));
